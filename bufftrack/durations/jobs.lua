--[[
    durations/jobs.lua

    Job ability, blood pact and Corsair roll duration estimates, computed
    from the PhoenixXI server's own numbers (durations/serverdata.lua,
    generated by tools/gen_durations.py).

    Server-side extras that depend on things the client can't see (merits
    and job points beyond what data.lua tracks, resistance rolls) are left
    out; the base duration plus any gear bonus is returned.
]]--

local loaded, server = pcall(require, 'durations.serverdata');
if (not loaded) then
    server = nil;
end

local jobs = {};

local SUMMONING_SKILL = 38;
local ROLL_BASE_DURATION = 300;

local function GearTotal(data, modName)
    local items = server.gear[modName];
    if (items == nil) or (modName == '') then
        return 0;
    end
    return data:EquipSum(items);
end

--Returns duration (seconds), status effect id -- or nil if there's no data
--for this ability.
function jobs.GetDuration(data, abilityId)
    if (server == nil) then
        return nil;
    end

    local row = server.abilities[abilityId];
    if (row ~= nil) then
        local duration = row.base + GearTotal(data, row.mod);
        if (row.summoning) then
            --Blood pact wards lengthen with summoning skill above 300 (up to +200).
            duration = duration + math.max(0, math.min(data:GetSkill(SUMMONING_SKILL) - 300, 200));
        end
        return duration, row.effect;
    end

    row = server.rolls[abilityId];
    if (row ~= nil) then
        local merit = server.merits.WINNING_STREAK;
        local duration = ROLL_BASE_DURATION
            + (data:GetMeritCount(merit.id) * merit.perRank)
            + GearTotal(data, 'PHANTOM_DURATION');
        return duration, row.effect;
    end

    return nil;
end

return jobs;
